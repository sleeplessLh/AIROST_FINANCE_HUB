#
#   [GitHub]
#     只有代码；.gitignore 排除了 instance/ 和 *.db，
#     所以数据库和收据不会被 push 上去
#
#   [Render 网站：airost-finance-hub-4jd2]
#     ④ 容器硬盘：从 GitHub 拉下来的代码 + 运行时写入的文件
#        ⚠️ 每次部署、重启都会被清空
#
#   [Render 数据库：airost-finance-db]
#     ⑤ PostgreSQL：线上所有正式数据，永久保存
#
#   另外：跑测试时，每个测试文件会在系统 Temp 文件夹建立临时 SQLite，
#   测试结束后删除，不会影响 ② 的开发数据库
#
# ------------------------------------------------------------
# 2. 数据库只有两种，由 DATABASE_URL 决定
# ------------------------------------------------------------
#
#   没有 DATABASE_URL → SQLite（②，本地开发）
#   有 DATABASE_URL   → PostgreSQL（⑤，Render 线上）
#
#   两个数据库彼此完全独立：
#     本地建立的账号（例如 TEST-M001）只存在 SQLite
#     线上建立的账号（例如 AIR-A001）只存在 PostgreSQL
#   规则：账号存在哪个数据库，就只能在连着那个数据库的网站登录
#
# ------------------------------------------------------------
# 3. 为什么 Render 的硬盘会被清空
# ------------------------------------------------------------
#
#   每次部署，Render 会：
#     1) 从 GitHub 拉最新代码
#     2) 建立一个全新的容器（像一台全新的小电脑）
#     3) pip install、启动 gunicorn
#     4) 丢掉旧的容器（旧容器硬盘上的文件一起消失）
#   免费方案闲置后休眠再启动，也会换新容器
#
#   比喻：
#     ④ 容器硬盘 = 酒店房间：退房就打扫干净，下一位房客什么都看不到
#     ⑤ PostgreSQL = 银行保险箱：独立在酒店之外，换几次房间东西都在
#
#   曾经因此发生的问题：
#     - 账号消失：线上没设 DATABASE_URL → 退回 SQLite → SQLite 在 ④ → 部署后清空
#     - 收据消失：收据图片写在 ④ → 部署后清空（B1 改为另存一份到 ⑤）
#
#   本地不会有这个问题：你的电脑不会被"打扫"，所以只有上线后才会暴露
#
#   规则：线上所有需要保留的东西，都必须存在 ⑤ PostgreSQL；
#         ④ 容器硬盘只能当快取，随时可能消失
#
# ------------------------------------------------------------
# 4. PostgreSQL 是什么
# ------------------------------------------------------------
#
#   PostgreSQL 是"数据库服务器"程序：一直在一台机器上运行，
#   专门负责保存数据，其他程序通过网络 + 账号密码连线来读写。
#   免费、开源、发展三十多年，非常稳定。
#
#   SQLite vs PostgreSQL：
#     SQLite      - 一个文件；程序直接打开读写；适合本地开发、小工具
#     PostgreSQL  - 一个服务器；通过网络连线；支持多人同时读写；适合正式网站
#
#   比喻：
#     SQLite     = 桌上的笔记本：自己拿起来就写，很方便
#     PostgreSQL = 图书馆柜台：出示借书证（账号密码），由馆员（服务器）帮你存取，
#                  很多人可以同时来柜台
#
#   同一份代码能用两种数据库，是因为中间有翻译层：
#     你的代码
#       → SQLAlchemy（ORM，把 Python 翻译成 SQL）
#       → 驱动程序（SQLite 用内建 sqlite3；PostgreSQL 用 psycopg2）
#       → 数据库
#   大部分差异由 SQLAlchemy 处理（例如 LargeBinary → BLOB / BYTEA），
#   但偶尔仍有差异：PostgreSQL 中 user 是保留字，手写 SQL 时要写成 "user"
#
# ------------------------------------------------------------
# 5. DATABASE_URL 格式
# ------------------------------------------------------------
#
#   postgresql+psycopg2://使用者名称:密码@主机地址/数据库名称
#     postgresql  → 数据库种类
#     +psycopg2   → 驱动程序（SQLAlchemy 2.1 默认改用 psycopg 第 3 版，所以必须写明）
#
#   Internal URL：只能在 Render 内部使用（网站用这个）
#   External URL：可以从自己的电脑连线（查询、维护时用）
#   ⚠️ URL 含有数据库密码，不能写进代码或 commit 到 GitHub
#
